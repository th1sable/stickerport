"""Bundle our three local modules as a classic script for WKWebView file origins."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]/'web'
core=(root/'core.js').read_text(encoding='utf-8')
core=re.sub(r'^export ', '', core, flags=re.M)
licenses=(root/'licenses.js').read_text(encoding='utf-8').replace('export default ', 'const licenses = ', 1)
app=(root/'app.js').read_text(encoding='utf-8')
app=re.sub(r'^import .*?;\r?\n', '', app, flags=re.M)
assert not re.search(r'^\s*(import|export)\b', core+licenses+app, re.M), 'Unhandled module declaration'
(root/'bundle.js').write_text("// Generated by scripts/build_web.py.\n(() => {\n'use strict';\n"+core+'\n'+licenses+'\n'+app+'\n})();\n',encoding='utf-8')
